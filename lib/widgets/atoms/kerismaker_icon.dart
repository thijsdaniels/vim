import 'package:flutter/material.dart';

const KerismakerStyle defaultStyle = KerismakerStyle.goofyFlat;

class KerismakerIcon {
  static Image network(
    String slug, {
    KerismakerStyle style = defaultStyle,
    double size = 32,
    Widget Function(BuildContext, Object, StackTrace?)? errorBuilder,
  }) {
    return Image.network(
      _url(slug, style),
      width: size,
      height: size,
      errorBuilder: errorBuilder ??
          (context, exception, trace) => SizedBox(
                width: size,
                height: size,
              ),
    );
  }

  static Image asset(
    String slug, {
    KerismakerStyle style = defaultStyle,
    double size = 32,
    Widget Function(BuildContext, Object, StackTrace?)? errorBuilder,
  }) {
    return Image(
      image: AssetImage(_path(slug, style)),
      width: size,
      height: size,
      errorBuilder: errorBuilder ??
          (context, exception, trace) => SizedBox(
                width: size,
                height: size,
              ),
    );
  }

  static String _url(String slug, KerismakerStyle style) {
    switch (style) {
      case KerismakerStyle.goofyFlat:
        return 'https://img.icons8.com/external-goofy-flat-kerismaker/100/null/$slug.png';
    }
  }

  static String _path(String slug, KerismakerStyle style) {
    switch (style) {
      case KerismakerStyle.goofyFlat:
        return 'assets/images/kerismaker/goofy-flat/kerismaker-$slug-100.png';
    }
  }
}

enum KerismakerStyle {
  goofyFlat,
}

